# ABOUTME: Checks Windows path budgets against the preserved reference filenames.
# ABOUTME: Verifies compact per-test paths remain unique and reject unsafe roots.

import os
import shutil
import sys
from pathlib import Path

import pytest

from practice.paths import REFERENCES_DIR
from tools.verification import check_windows_path, run_check


def test_compact_fixture_can_copy_all_reference_bytes(tmp_path: Path) -> None:
    assert tmp_path.name.startswith("t")
    assert len(tmp_path.name) < 10
    target = tmp_path / "references"
    shutil.copytree(
        REFERENCES_DIR, target, ignore=shutil.ignore_patterns("__pycache__")
    )
    for source in REFERENCES_DIR.rglob("*"):
        if (
            source.is_file()
            and "__pycache__" not in source.relative_to(REFERENCES_DIR).parts
        ):
            assert (
                target / source.relative_to(REFERENCES_DIR)
            ).read_bytes() == source.read_bytes()


def test_overlong_windows_destination_has_actionable_diagnostic(tmp_path: Path) -> None:
    root = tmp_path / ("nested-" * 25)
    if sys.platform == "win32":
        with pytest.raises(AssertionError, match="Set TEMP and TMP") as failure:
            check_windows_path(root, REFERENCES_DIR)
        assert "independently of --basetemp" in str(failure.value)
        assert "0121-best-time-to-buy-and-sell-stock-function.py" in str(failure.value)
        assert not root.exists()
    else:
        check_windows_path(root, REFERENCES_DIR)


def test_successful_verification_command(tmp_path: Path) -> None:
    run_check([sys.executable, "-c", "print('verified')"], tmp_path, {}, 10)


def test_windows_path_budget_counts_utf16_units(tmp_path: Path) -> None:
    if os.name != "nt":
        return
    longest = max(
        (
            path.relative_to(REFERENCES_DIR.parent)
            for path in REFERENCES_DIR.rglob("*")
            if path.is_file()
            and "__pycache__" not in path.relative_to(REFERENCES_DIR).parts
        ),
        key=lambda path: len(str(path).encode("utf-16-le")) // 2,
    )
    base_units = len(str(tmp_path.resolve() / longest).encode("utf-16-le")) // 2
    # The added component contributes its separator and two code units per emoji.
    emoji_count = (260 - (base_units + 1) + 1) // 2
    root = tmp_path / ("\U0001f680" * emoji_count)
    destination = root.resolve() / longest
    assert len(str(destination)) < 260
    assert len(str(destination).encode("utf-16-le")) // 2 >= 260
    with pytest.raises(AssertionError, match="Set TEMP and TMP"):
        check_windows_path(root, REFERENCES_DIR)
    assert not root.exists()


def test_reference_budget_excludes_generated_bytecode(tmp_path: Path) -> None:
    references = tmp_path / "references"
    references.mkdir()
    source = references / "solution.py"
    source.write_bytes(b"# preserved reference bytes\n")
    cache = references / "__pycache__"
    cache.mkdir()
    (cache / ("solution" * 12 + ".cpython-313.pyc")).write_bytes(b"generated bytecode")
    destination = tmp_path / ("destination-" * 7)
    check_windows_path(destination, references, extra=20)
    shutil.copytree(
        references,
        destination / "references",
        ignore=shutil.ignore_patterns("__pycache__"),
    )
    assert (
        destination / "references" / "solution.py"
    ).read_bytes() == source.read_bytes()
    assert not (destination / "references" / "__pycache__").exists()
